"""Optional PostgreSQL adapter for SANG GIAO AI. Experimental: staging only."""
import re
import sqlite3
import psycopg
from psycopg.rows import dict_row

class Record(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)

def record_factory(cursor):
    names=[x.name for x in cursor.description]
    def make(values):
        return Record(zip(names,values))
    return make

def normalize(sql):
    sql=sql.strip()
    if sql.upper().startswith('PRAGMA '):
        return 'SELECT 1'
    sql=re.sub(r'\bINTEGER PRIMARY KEY\b', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',sql, flags=re.I)
    sql=re.sub(r'\bDEFAULT CURRENT_TIMESTAMP\b', 'DEFAULT (CURRENT_TIMESTAMP::text)',sql,flags=re.I)
    sql=re.sub(r'^INSERT OR IGNORE INTO\s+', 'INSERT INTO ',sql, flags=re.I)
    ignore=bool(re.match(r'^INSERT OR IGNORE',sql,flags=re.I))
    # ignore must be captured BEFORE removing the SQLite prefix
    sql=sql.replace('exclude.', 'excluded.')
    sql=sql.replace('?', '%s')
    return sql

class Cursor:
    def __init__(self, raw, lastrowid=None):
        self.raw=raw;self.lastrowid=lastrowid
    def fetchone(self):return self.raw.fetchone()
    def fetchall(self):return self.raw.fetchall()
    def __iter__(self):return iter(self.raw)
    @property
    def rowcount(self):return self.raw.rowcount

class Connection:
    def __init__(self, url, schema='public'):
        self.conn=psycopg.connect(url,row_factory=record_factory,connect_timeout=10)
        if schema!='public':
            if not re.fullmatch(r'teacher_[0-9a-f]{64}',schema):
                raise ValueError('Unsafe tenant identifier')
            self.conn.execute('CREATE SCHEMA IF NOT EXISTS "'+schema+'"')
            self.conn.execute('SET search_path TO "'+schema+'"')
    def execute(self, sql, params=()):
        ignore=bool(re.match(r'^\s*INSERT OR IGNORE INTO',sql,flags=re.I))
        transformed=normalize(sql)
        if ignore:transformed+=' ON CONFLICT DO NOTHING'
        insert=bool(re.match(r'^INSERT INTO',transformed,flags=re.I))
        # Preserve sqlite Cursor.lastrowid for simple inserts.
        with_return=insert and not ignore and bool(re.match(r'^INSERT INTO\\s+(users|classes|students|questions|exams|attempts|games|lesson_media)\\b',transformed,flags=re.I)) and 'RETURNING' not in transformed.upper()
        if with_return:transformed+=' RETURNING id'
        try:
            cur=self.conn.execute(transformed,params)
        except psycopg.errors.UniqueViolation as error:
            raise sqlite3.IntegrityError(str(error)) from error
        last=None
        if with_return:
            row=cur.fetchone()
            last=row['id'] if row else None
        return Cursor(cur,last)
    def executemany(self, sql, seq):
        transformed=normalize(sql)
        if re.match(r'^\s*INSERT OR IGNORE INTO',sql,flags=re.I):
            transformed+=' ON CONFLICT DO NOTHING'
        try:return self.conn.executemany(transformed,seq)
        except psycopg.errors.UniqueViolation as error:
            raise sqlite3.IntegrityError(str(error)) from error
    def executescript(self, script):
        for statement in script.split(';'):
            if statement.strip():
                self.conn.execute(normalize(statement))
    def __enter__(self):return self
    def __exit__(self, typ, value, tb):
        try:
            if typ is None:self.conn.commit()
            else:self.conn.rollback()
        finally:self.conn.close()
