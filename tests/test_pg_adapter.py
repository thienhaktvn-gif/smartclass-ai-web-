import unittest
from pgadapter import normalize

class PgAdapterSmoke(unittest.TestCase):
 def test_placeholder_and_identity(self):
  q=normalize('CREATE TABLE IF NOT EXISTS classes(id INTEGER PRIMARY KEY,name TEXT NOT NULL UNIQUE)')
  self.assertIn('GENERATED BY DEFAULT AS IDENTITY',q)
 def test_parameters(self):
  self.assertEqual(normalize('SELECT * FROM students WHERE code=?'),'SELECT * FROM students WHERE code=%s')
 def test_ignore(self):
  self.assertEqual(normalize('INSERT OR IGNORE INTO classes(name) VALUES(?)'),'INSERT INTO classes(name) VALUES(%s)')
 def test_timestamp(self):
  self.assertIn('CURRENT_TIMESTAMP::text',normalize('CREATE TABLE t(created TEXT DEFAULT CURRENT_TIMESTAMP)'))

if __name__=='__main__':unittest.main()
